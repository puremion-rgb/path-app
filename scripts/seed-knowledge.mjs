async function main() {
  getDb(); // 테이블 생성 보장

  const existing = countKnowledgeDocs();
  if (existing > 0) {
    console.log(`이미 KnowledgeDoc이 ${existing}건 있습니다. 중복 삽입을 피하려면 data/app.db를 지우고 다시 실행하세요.`);
    return;
  }

  console.log(`RAG 지식베이스 ${DOCS.length}건 임베딩 중... (Gemini API 호출)`);
  for (const doc of DOCS) {
    const embedding = await embedText(`${doc.title}\n${doc.content}`);
    insertKnowledgeDoc({ ...doc, embedding });
    console.log(`  - ${doc.title} 저장 완료 (dim=${embedding.length})`);
  }
  console.log("완료!");
}

main().catch((err) => {
  console.error("시드 실패:", err.message);
  process.exit(1);
});
